def seed(username: str) -> None:
    if MANIFEST_PATH.exists():
        raise SystemExit(
            f"{MANIFEST_PATH.name} already exists -- looks like demo data was already seeded. "
            f"Run `python seed_demo_data.py --cleanup` first if you want to reseed."
        )

    conn = psycopg2.connect(DB_URL)
    conn.autocommit = False
    manifest = build_manifest()
    manifest["amit_username"] = username
    try:
        cur = conn.cursor()
        amit_id = get_user_id(cur, username)
        log(f"Seeding demo data for '{username}' (user_id {amit_id})")
        amit_persona = ("The main user -- balanced, friendly, generally upbeat but occasionally "
                         "stressed with work, texts in a normal casual style.")

        friends = create_friends(cur, manifest)
        create_friendships(cur, amit_id, friends)
        total_messages = seed_direct_messages(cur, amit_id, amit_persona, friends, manifest)
        conv_ids = seed_conversations(cur, amit_id, manifest)
        seed_tasks(cur, amit_id, conv_ids, manifest)
        seed_legacy_ei(cur, amit_id, friends, conv_ids, manifest)

        bulk_friends = create_bulk_friends(cur, manifest, friends, n=100)
        bulk_messages = create_bulk_friendships_and_messages(cur, amit_id, bulk_friends, manifest)
        seed_bulk_profiles_and_mood(cur, amit_id, bulk_friends, manifest)
        total_messages += bulk_messages

        all_friends = friends + bulk_friends
        seed_new_ei_schema(cur, amit_id, all_friends, manifest)
        seed_calls(cur, amit_id, all_friends, manifest)

        conn.commit()
        MANIFEST_PATH.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        log(f"Done. {len(all_friends)} friends total ({len(friends)} rich + {len(bulk_friends)} bulk), "
            f"{total_messages} direct messages across {len(friends) + len(FRIEND_FRIEND_PAIRS) + len(bulk_friends)} threads.")
        log(f"Manifest written to {MANIFEST_PATH} -- run --cleanup anytime to remove all of this.")
        log("Note: NUDGE_FEATURE_ENABLED=False in .env -- flip it to true if you want the "
            "overdue-task/mood-trend/relationship nudges to actually fire off this data.")
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def cleanup() -> None:
    if not MANIFEST_PATH.exists():
        raise SystemExit(f"No {MANIFEST_PATH.name} found -- nothing to clean up.")
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))

    conn = psycopg2.connect(DB_URL)
    conn.autocommit = False
    try:
        cur = conn.cursor()
        log(f"Deleting {len(manifest['friend_user_ids'])} fake friend accounts (cascades their friendships, "
            "sent/received messages, own mood history, and EI subjects/facts/relationship rows)...")
        if manifest["friend_user_ids"]:
            cur.execute("DELETE FROM users WHERE id = ANY(%s)", (manifest["friend_user_ids"],))

        # Everything below is owned by Amit's own account, so it's cleaned
        # up explicitly by id rather than relying on any cascade.
        table_id_pairs = [
            ("direct_messages", "direct_message_ids"),
            ("personality_notes", "personality_note_ids"),
            ("mood_logs", "mood_log_ids"),
            ("tasks", "task_ids"),
            ("speaker_profiles", "speaker_profile_ids"),
            ("conversations", "conversation_ids"),
            ("calls", "call_ids"),  # call_participants cascade-deletes via calls.id
        ]
        for table, key in table_id_pairs:
            ids = manifest.get(key) or []
            if ids:
                cur.execute(f"DELETE FROM {table} WHERE id = ANY(%s)", (ids,))

        ei_table_id_pairs = [
            ("emotional_intelligence.relationship_profiles", "ei_relationship_profile_ids"),
            ("emotional_intelligence.personality_snapshots", "ei_personality_snapshot_ids"),
            ("emotional_intelligence.preferences", "ei_preference_ids"),
            ("emotional_intelligence.memories", "ei_memory_ids"),
            ("emotional_intelligence.beliefs", "ei_belief_ids"),
            ("emotional_intelligence.facts", "ei_fact_ids"),
        ]
        for table, key in ei_table_id_pairs:
            ids = manifest.get(key) or []
            if ids:
                cur.execute(f"DELETE FROM {table} WHERE id = ANY(%s)", (ids,))

        # Amit's own EI subject row (friends' own subject rows are already
        # gone via the CASCADE from deleting their user row above).
        amit_id = get_user_id(cur, manifest["amit_username"])
        cur.execute(
            "DELETE FROM emotional_intelligence.app_user_subject_links WHERE user_id = %s RETURNING subject_id",
            (amit_id,),
        )
        row = cur.fetchone()
        if row:
            cur.execute("DELETE FROM emotional_intelligence.subjects WHERE id = %s", (row[0],))

        conn.commit()
        log("Cleanup complete.")
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

    MANIFEST_PATH.unlink()
    log(f"Removed {MANIFEST_PATH.name}.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--username", default="amit", help="Existing account to seed friends/data for (default: amit)")
    parser.add_argument("--cleanup", action="store_true", help="Delete everything this script previously seeded")
    args = parser.parse_args()

    if args.cleanup:
        cleanup()
    else:
        seed(args.username)


if __name__ == "__main__":
    main()
