def generate_bulk_friends(n: int, used_photo_men: set, used_photo_women: set) -> list[dict]:
    pairs_used = set()
    results = []
    men_pool = [i for i in range(100) if i not in used_photo_men]
    women_pool = [i for i in range(100) if i not in used_photo_women]
    random.shuffle(men_pool)
    random.shuffle(women_pool)
    mi = fi = 0
    while len(results) < n:
        gender = random.choice(["men", "women"])
        first = random.choice(BULK_FIRST_MALE if gender == "men" else BULK_FIRST_FEMALE)
        last = random.choice(BULK_LAST)
        key = (first, last)
        if key in pairs_used:
            continue
        pairs_used.add(key)
        if gender == "men":
            photo = men_pool[mi]
            mi += 1
        else:
            photo = women_pool[fi]
            fi += 1
        results.append({
            "first": first, "last": last, "gender": gender, "photo": photo,
            "trait": random.choice(BULK_TRAITS),
        })
    return results


def generate_bulk_conversation(n_messages: int) -> list[dict]:
    turns: list[tuple] = []
    while len(turns) < n_messages:
        turns.extend(random.choice(BULK_EXCHANGE_TEMPLATES))
    return [{"speaker": s, "text": t} for t, s in turns[:n_messages]]


