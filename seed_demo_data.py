        # these accounts need to read as real friends when showcasing the
        # app, not as obviously-seeded test data.
        username = f"{f['first'].lower()}_{f['last'].lower()}"
        email = f"{f['first'].lower()}.{f['last'].lower()}@example.invalid"
        password_hash = generate_password_hash("sandbox-seed-account-not-a-real-login")
