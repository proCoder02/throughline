# ============================================================================
# Ollama Cloud call -- same endpoint/convention as
# emotional_intelligence/extraction_pipeline.py's call_llm, reused directly
# here rather than reimplemented a third time.
# ============================================================================
def call_llm(messages: list[dict]) -> str:
    if not OLLAMA_API_KEY:
        raise RuntimeError("Missing Ollama API key (OLLAMA_API_KEY / olama_api_key in .env)")
    response = requests.post(
        "https://ollama.com/api/chat",
        headers={"Authorization": f"Bearer {OLLAMA_API_KEY}", "Content-Type": "application/json"},
        json={"model": OLLAMA_MODEL, "messages": messages, "stream": False},
        timeout=180,
    )
    response.raise_for_status()
    return response.json().get("message", {}).get("content", "")


def extract_json_array(text: str) -> list | None:
    text = text.strip()
    text = re.sub(r"^```json\s*|^```\s*|```$", "", text, flags=re.MULTILINE).strip()
    try:
        return json.loads(text)
    except ValueError:
        pass
    match = re.search(r"\[.*\]", text, re.DOTALL)
    if match:
        try:
            return json.loads(match.group(0))
        except ValueError:
            return None
    return None


def generate_conversation(name_a: str, persona_a: str, name_b: str, persona_b: str, topic: str, n_messages: int) -> list[dict]:
    """Returns [{"speaker": "A"|"B", "text": "..."}], via Ollama, with a
    hand-written fallback if the call or parsing fails so seeding never
    hard-crashes on a flaky LLM call."""
    prompt = f"""Write a realistic WhatsApp-style text conversation between two Indian friends.

Person A ({name_a}): {persona_a}
Person B ({name_b}): {persona_b}
Topic: {topic}

Rules:
- Exactly {n_messages} messages total, alternating naturally (occasional back-to-back double-texts from the same person are fine, real chats aren't strictly ping-pong).
- Short, casual, real texting style -- not paragraphs. Occasional Hinglish words are fine (yaar, arre, bhai, acha) but keep it readable.
- Each person's tone must clearly reflect their personality described above.
- Absolutely NO mention of sending, sharing, or receiving photos, images, videos, voice notes, or any attachment -- text only, always.
- Reply with ONLY a JSON array, no preamble, no code fences: [{{"speaker": "A", "text": "..."}}, ...]
- "speaker" must be exactly "A" or "B"."""

    try:
        content = call_llm([{"role": "user", "content": prompt}])
        parsed = extract_json_array(content)
        if parsed and isinstance(parsed, list) and len(parsed) >= 3:
            cleaned = []
            for turn in parsed:
                speaker = turn.get("speaker")
                text = (turn.get("text") or "").strip()
                if speaker in ("A", "B") and text:
                    cleaned.append({"speaker": speaker, "text": text})
            if cleaned:
                return cleaned
    except Exception as exc:
        log(f"  LLM call failed ({exc}), using fallback template for this thread")

    # Fallback -- generic but still two-sided, never leaves a thread empty.
    fallback = [
        ("A", f"heyy, {topic}?"),
        ("B", "haha yeah tell me"),
        ("A", "so what do you think, are you in?"),
        ("B", "100%, count me in"),
        ("A", "perfect, will confirm details soon"),
        ("B", "sounds good!"),
    ]
    return [{"speaker": s, "text": t} for s, t in fallback[:n_messages]]


# ============================================================================
# Timestamp helper -- spreads a thread's messages realistically over the
# last ~10 days, ending recently, with occasional multi-hour/day gaps
# between message clusters instead of one dense burst.
# ============================================================================
def spread_timestamps(n: int, days_back: int = 10) -> list[datetime]:
    now = datetime.now().astimezone()
    start = now - timedelta(days=days_back, hours=random.randint(0, 12))
    stamps = [start]
    for _ in range(n - 1):
        gap_minutes = random.choice([random.randint(1, 15)] * 6 + [random.randint(60, 240)] * 3 + [random.randint(600, 2400)])
        nxt = stamps[-1] + timedelta(minutes=gap_minutes)
        if nxt > now:
            nxt = now - timedelta(minutes=random.randint(0, 30))
        stamps.append(nxt)
    stamps.sort()
    return stamps


