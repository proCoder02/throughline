def seed_new_ei_schema(cur, amit_id: int, friends: list[dict], manifest: dict) -> None:
    """emotional_intelligence.* -- powers the weekly digest and the friend
    relationship-insight surfaced in GET /friends/<id>/mood."""
    log("Applying emotional_intelligence schema (idempotent) and seeding subjects/facts/relationships...")
    if SCHEMA_SQL_PATH.exists():
        cur.execute(SCHEMA_SQL_PATH.read_text(encoding="utf-8"))

    def ensure_subject(user_id: int) -> int:
        canonical = f"app_user:{user_id}"
        cur.execute(
            "INSERT INTO emotional_intelligence.subjects (canonical_name, source) VALUES (%s, 'app_user') "
            "ON CONFLICT (canonical_name) DO UPDATE SET canonical_name = EXCLUDED.canonical_name RETURNING id",
            (canonical,),
        )
        subject_id = cur.fetchone()[0]
        manifest["ei_subject_ids"].append(subject_id)
        cur.execute(
            "INSERT INTO emotional_intelligence.app_user_subject_links (user_id, subject_id) VALUES (%s, %s) "
            "ON CONFLICT (user_id) DO UPDATE SET subject_id = EXCLUDED.subject_id",
            (user_id, subject_id),
        )
        return subject_id

    amit_subject = ensure_subject(amit_id)
    now = datetime.now().astimezone()

    for predicate, obj in AMIT_FACTS:
        cur.execute(
            "INSERT INTO emotional_intelligence.facts (subject_id, subject, predicate, object, confidence, created_at) "
            "VALUES (%s, 'Amit', %s, %s, 0.9, %s) RETURNING id",
            (amit_subject, predicate, obj, now - timedelta(days=random.randint(0, 5))),
        )
        manifest["ei_fact_ids"].append(cur.fetchone()[0])

    for topic, belief in AMIT_BELIEFS:
        cur.execute(
            "INSERT INTO emotional_intelligence.beliefs (subject_id, topic, belief, confidence, created_at) "
            "VALUES (%s, %s, %s, 0.85, %s) RETURNING id",
            (amit_subject, topic, belief, now - timedelta(days=random.randint(0, 5))),
        )
        manifest["ei_belief_ids"].append(cur.fetchone()[0])

    for summary, emotion, importance in AMIT_MEMORIES:
        cur.execute(
            "INSERT INTO emotional_intelligence.memories (subject_id, summary, emotion, importance, created_at) "
            "VALUES (%s, %s, %s, %s, %s) RETURNING id",
            (amit_subject, summary, emotion, importance, now - timedelta(days=random.randint(0, 5))),
        )
        manifest["ei_memory_ids"].append(cur.fetchone()[0])

    for category, item in AMIT_PREFERENCES:
        cur.execute(
            "INSERT INTO emotional_intelligence.preferences (subject_id, category, item, weight, confidence, updated_at) "
            "VALUES (%s, %s, %s, 0.8, 0.85, %s) "
            "ON CONFLICT (subject_id, category, item) DO UPDATE SET updated_at = EXCLUDED.updated_at RETURNING id",
            (amit_subject, category, item, now),
        )
        manifest["ei_preference_ids"].append(cur.fetchone()[0])

    cur.execute(
        "INSERT INTO emotional_intelligence.personality_snapshots "
        "(subject_id, openness, conscientiousness, extraversion, agreeableness, neuroticism, confidence, created_at) "
        "VALUES (%s, 0.72, 0.68, 0.55, 0.8, 0.4, 0.75, %s) RETURNING id",
        (amit_subject, now),
    )
    manifest["ei_personality_snapshot_ids"].append(cur.fetchone()[0])

