def create_bulk_friendships_and_messages(cur, amit_id: int, bulk_friends: list[dict], manifest: dict) -> int:
    log("Creating friendships + templated message threads for bulk friends...")
    total = 0
    for f in bulk_friends:
        full_name = f"{f['first']} {f['last']}"
        cur.execute(
            "INSERT INTO friendships (user_id, friend_id, nickname) VALUES (%s, %s, %s), (%s, %s, NULL) "
            "ON CONFLICT DO NOTHING",
            (amit_id, f["user_id"], full_name, f["user_id"], amit_id),
        )
        n = random.randint(4, 8)
        turns = generate_bulk_conversation(n)
        stamps = spread_timestamps(len(turns), days_back=14)
        for k, (turn, ts) in enumerate(zip(turns, stamps)):
            sender_id = amit_id if turn["speaker"] == "A" else f["user_id"]
            recipient_id = f["user_id"] if turn["speaker"] == "A" else amit_id
            # Leave the last message's tick state unset, same convention as
            # the rich threads -- a thread where every single message is
            # already double-blue-ticked isn't realistic metadata.
            is_recent = k == len(turns) - 1
            delivered = None if is_recent else ts + timedelta(seconds=random.randint(5, 40))
            read = None if is_recent else ts + timedelta(seconds=random.randint(60, 600))
            cur.execute(
                "INSERT INTO direct_messages (sender_id, recipient_id, content, created_at, delivered_at, read_at) "
                "VALUES (%s, %s, %s, %s, %s, %s) RETURNING id",
                (sender_id, recipient_id, turn["text"], ts, delivered, read),
            )
            manifest["direct_message_ids"].append(cur.fetchone()[0])
            total += 1
    return total


def seed_calls(cur, amit_id: int, friends: list[dict], manifest: dict) -> int:
    """calls/call_participants -- backs GET /friends' call_count/last_call_at/
    last_call_outgoing (see app.py's friends-list query) and the "Calls"/
    "Last call" rows on the Your World detail card, which otherwise always
    read "No calls yet"/"Never" since nothing else in this script touches
    these tables."""
    log("Seeding call history (calls/call_participants)...")
    total = 0
    now = datetime.now().astimezone()
    for f in friends:
        for i in range(random.randint(1, 3)):
            started = now - timedelta(days=random.randint(0, 13), hours=random.randint(0, 23),
                                       minutes=random.randint(0, 59))
            ended = started + timedelta(minutes=random.randint(1, 25))
            initiator_id = random.choice([amit_id, f["user_id"]])
            room_name = f"call-{amit_id}-{f['user_id']}-{i}-{random.randint(100000, 999999)}"
            cur.execute(
                "INSERT INTO calls (initiator_user_id, room_name, category, status, created_at, ended_at) "
                "VALUES (%s, %s, 'personal', 'ended', %s, %s) RETURNING id",
                (initiator_id, room_name, started, ended),
            )
            call_id = cur.fetchone()[0]
            manifest["call_ids"].append(call_id)
            cur.execute(
                "INSERT INTO call_participants (call_id, user_id, status, joined_at, left_at) "
                "VALUES (%s, %s, 'joined', %s, %s), (%s, %s, 'joined', %s, %s)",
                (call_id, amit_id, started, ended,
                 call_id, f["user_id"], started + timedelta(seconds=random.randint(2, 15)), ended),
            )
            total += 1
    return total


def seed_bulk_profiles_and_mood(cur, amit_id: int, bulk_friends: list[dict], manifest: dict) -> None:
    log("Seeding lightweight Profiles-tab data and mood history for bulk friends...")
    now = datetime.now().astimezone()
    for f in bulk_friends:
        cur.execute(
            "INSERT INTO speaker_profiles (user_id, name) VALUES (%s, %s) "
            "ON CONFLICT (user_id, name) DO UPDATE SET name = EXCLUDED.name RETURNING id",
            (amit_id, f["first"]),
        )
        profile_id = cur.fetchone()[0]
        manifest["speaker_profile_ids"].append(profile_id)

        cur.execute(
            "INSERT INTO personality_notes (user_id, speaker_label, observation, profile_id) "
            "VALUES (%s, %s, %s, %s) RETURNING id",
            (amit_id, f["first"], f["trait"], profile_id),
        )
        manifest["personality_note_ids"].append(cur.fetchone()[0])

        cur.execute(
            "INSERT INTO profile_categories (profile_id, category, first_seen_at, last_seen_at) "
            "VALUES (%s, 'personal', %s, %s) ON CONFLICT (profile_id, category) DO NOTHING",
            (profile_id, now - timedelta(days=10), now),
        )

        # Two entries, not one -- compute_compiled_mood only looks at the
        # live 2-hour bucket or today's most recent entry (app.py's
        # friend_mood). A single entry randomly placed up to 20 hours back
        # often lands before local midnight and shows "Not enough recent
        # data"; anchoring one close to now guarantees a hit either way.
        moods = random.sample(MOOD_LABELS, 2)
        cur.execute(
            "INSERT INTO mood_logs (user_id, mood_label, mood_score, created_at) VALUES (%s, %s, %s, %s) RETURNING id",
            (f["user_id"], moods[0], round(random.uniform(0.6, 0.9), 2), now - timedelta(minutes=random.randint(5, 90))),
        )
        manifest["mood_log_ids"].append(cur.fetchone()[0])
        cur.execute(
            "INSERT INTO mood_logs (user_id, mood_label, mood_score, created_at) VALUES (%s, %s, %s, %s) RETURNING id",
            (f["user_id"], moods[1], round(random.uniform(0.6, 0.9), 2), now - timedelta(hours=random.randint(6, 14))),
        )
        manifest["mood_log_ids"].append(cur.fetchone()[0])


def seed_direct_messages(cur, amit_id: int, amit_persona: str, friends: list[dict], manifest: dict) -> int:
    log("Generating direct-message threads (this calls the LLM per thread, takes a few minutes)...")
    total = 0

    for f in friends:
        n = random.randint(9, 14)
        topic = random.choice(f["topics"])
        log(f"  Amit <-> {f['first']}: {n} messages about '{topic}'")
        turns = generate_conversation("A", amit_persona, "B", f["archetype"], topic, n)
        stamps = spread_timestamps(len(turns))
        for k, (turn, ts) in enumerate(zip(turns, stamps)):
            sender_id = amit_id if turn["speaker"] == "A" else f["user_id"]
            recipient_id = f["user_id"] if turn["speaker"] == "A" else amit_id
            is_recent = k >= len(turns) - 2
            delivered = None if is_recent else ts + timedelta(seconds=random.randint(5, 40))
            read = None if is_recent else ts + timedelta(seconds=random.randint(60, 600))
            cur.execute(
                "INSERT INTO direct_messages (sender_id, recipient_id, content, created_at, delivered_at, read_at) "
                "VALUES (%s, %s, %s, %s, %s, %s) RETURNING id",
                (sender_id, recipient_id, turn["text"], ts, delivered, read),
            )
            manifest["direct_message_ids"].append(cur.fetchone()[0])
            total += 1

    for i, j in FRIEND_FRIEND_PAIRS:
        fa, fb = friends[i], friends[j]
        n = random.randint(8, 12)
        topic = random.choice(fa["topics"] + fb["topics"])
        log(f"  {fa['first']} <-> {fb['first']}: {n} messages about '{topic}'")
        turns = generate_conversation("A", fa["archetype"], "B", fb["archetype"], topic, n)
        stamps = spread_timestamps(len(turns), days_back=6)
        for turn, ts in zip(turns, stamps):
            sender_id = fa["user_id"] if turn["speaker"] == "A" else fb["user_id"]
            recipient_id = fb["user_id"] if turn["speaker"] == "A" else fa["user_id"]
            cur.execute(
                "INSERT INTO direct_messages (sender_id, recipient_id, content, created_at, delivered_at, read_at) "
                "VALUES (%s, %s, %s, %s, %s, %s) RETURNING id",
                (sender_id, recipient_id, turn["text"], ts,
                 ts + timedelta(seconds=20), ts + timedelta(seconds=200)),
            )
            manifest["direct_message_ids"].append(cur.fetchone()[0])
            total += 1

    return total


